    private void jSlider1StateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_jSlider1StateChanged
        int waterLevel = jSlider1.getValue();
        lblValue.setText("Water Level: " + waterLevel);
        LocalDate date = LocalDate.now();
        LocalTime time = LocalTime.now();

        DateTimeFormatter dateFormat =
                DateTimeFormatter.ofPattern("yyyy-MM-dd");

        DateTimeFormatter timeFormat =
                DateTimeFormatter.ofPattern("HH:mm:ss");

        String currentDate = date.format(dateFormat);
        String currentTime = time.format(timeFormat);

        lblDate.setText("Date: " + currentDate);
        lblTime.setText("Time: " + currentTime);

        if (waterLevelObservable != null) {
            waterLevelObservable.setWaterLevel(
                    waterLevel, currentDate, currentTime);
        }
    }//GEN-LAST:event_jSlider1StateChanged

